import type { Page } from 'playwright';
import { AppError } from '../../shared/http/errors.js';
import { withFacebookBrowserPage } from './facebook-browser.js';
import { requireFacebookVideoId } from './facebook-url.js';

/**
 * Verified on https://www.facebook.com/reel/<id> (logged out): the server-rendered page embeds the
 * Relay data as `<script type="application/json">` blobs. The `playback_video` object whose `id`
 * equals the reel id carries:
 * - `videoDeliveryLegacyFields.browser_native_hd_url` / `browser_native_sd_url` (progressive mp4, audio included)
 * - `thumbnailImage.uri`
 * - `video_available_captions_locales[]` = `{ locale, captions_url (vtt), localized_creation_method }`
 * - `length_in_second`
 * The CDN URLs are signed and expire, so they are resolved right before downloading.
 */
const NAV_TIMEOUT_MS = 45_000;
const CACHE_TTL_MS = 10 * 60_000;

export interface FacebookCaptionTrack {
  /** Facebook locale, e.g. `en_US`. */
  locale: string;
  url: string;
  autoGenerated: boolean;
}

export interface FacebookReelMedia {
  id: string;
  /** Best available progressive mp4 (HD when present, otherwise SD). */
  videoUrl: string;
  thumbnailUrl?: string;
  captions: FacebookCaptionTrack[];
  durationSec?: number;
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function str(value: unknown): string | undefined {
  return typeof value === 'string' && value ? value : undefined;
}

function parseCaptions(raw: unknown): FacebookCaptionTrack[] {
  if (!Array.isArray(raw)) return [];
  const tracks: FacebookCaptionTrack[] = [];
  for (const item of raw) {
    if (!isRecord(item)) continue;
    const url = str(item.captions_url);
    const locale = str(item.locale);
    if (!url || !locale) continue;
    tracks.push({ locale, url, autoGenerated: /auto/i.test(str(item.localized_creation_method) ?? '') });
  }
  return tracks;
}

function mapPlaybackVideo(node: Record<string, unknown>, id: string): FacebookReelMedia | null {
  const delivery = isRecord(node.videoDeliveryLegacyFields) ? node.videoDeliveryLegacyFields : undefined;
  const videoUrl = str(delivery?.browser_native_hd_url) ?? str(delivery?.browser_native_sd_url);
  if (!videoUrl) return null;

  const thumbnail = isRecord(node.thumbnailImage) ? str(node.thumbnailImage.uri) : undefined;
  return {
    id,
    videoUrl,
    thumbnailUrl: thumbnail,
    captions: parseCaptions(node.video_available_captions_locales),
    durationSec: typeof node.length_in_second === 'number' ? node.length_in_second : undefined,
  };
}

function findPlaybackVideo(doc: unknown, id: string): FacebookReelMedia | null {
  if (Array.isArray(doc)) {
    for (const item of doc) {
      const found = findPlaybackVideo(item, id);
      if (found) return found;
    }
    return null;
  }
  if (!isRecord(doc)) return null;

  if (doc.id === id && isRecord(doc.videoDeliveryLegacyFields)) {
    const media = mapPlaybackVideo(doc, id);
    if (media) return media;
  }
  for (const value of Object.values(doc)) {
    const found = findPlaybackVideo(value, id);
    if (found) return found;
  }
  return null;
}

async function readReelMedia(page: Page, id: string): Promise<FacebookReelMedia | null> {
  await page.goto(`https://www.facebook.com/reel/${id}`, { waitUntil: 'domcontentloaded', timeout: NAV_TIMEOUT_MS });
  const blobs = await page.$$eval('script[type="application/json"]', (scripts) =>
    scripts.map((script) => script.textContent ?? '').filter((text) => text.includes('browser_native_')),
  );

  for (const blob of blobs) {
    try {
      const media = findPlaybackVideo(JSON.parse(blob), id);
      if (media) return media;
    } catch {
      /* not a standalone JSON document */
    }
  }
  return null;
}

const cache = new Map<string, { media: FacebookReelMedia; expiresAt: number }>();

/**
 * Resolves the downloadable media of a Facebook reel. Results are cached briefly so downloading
 * video + audio + transcript + thumbnail of one reel opens the browser only once.
 */
export async function resolveFacebookReelMedia(url: string): Promise<FacebookReelMedia> {
  const id = requireFacebookVideoId(url);

  const cached = cache.get(id);
  if (cached && cached.expiresAt > Date.now()) return cached.media;

  const { value: media } = await withFacebookBrowserPage((page) => readReelMedia(page, id));
  if (!media) {
    throw new AppError(
      'Could not find the video on the Facebook reel page (private, removed, or login required)',
      502,
      'FACEBOOK_REEL_UNAVAILABLE',
    );
  }

  cache.set(id, { media, expiresAt: Date.now() + CACHE_TTL_MS });
  return media;
}
